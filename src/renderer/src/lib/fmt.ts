// Formatadores puros compartilhados (sem DOM, sem IPC) — ficam separados de
// ops.ts para poderem ser importados por módulos testáveis em node:test.
// ops.ts reexporta tudo daqui: os imports existentes de './lib/ops' continuam valendo.

export function fmtBytes(n: number | undefined | null): string {
  if (n == null || !Number.isFinite(n)) return '—'
  const u = ['B', 'KB', 'MB', 'GB', 'TB']
  let i = 0
  let v = n
  while (v >= 1024 && i < u.length - 1) {
    v /= 1024
    i++
  }
  return `${v >= 100 || i === 0 ? v.toFixed(0) : v.toFixed(1)} ${u[i]}`
}

export function fmtUptime(sec: number): string {
  const d = Math.floor(sec / 86400)
  const h = Math.floor((sec % 86400) / 3600)
  const m = Math.floor((sec % 3600) / 60)
  return d ? `${d}d ${h}h` : h ? `${h}h ${m}m` : `${m}m`
}
